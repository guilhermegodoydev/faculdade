    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
        String[] campos = {"RM", "ALUNO", "CURSO"};
        
        DefaultTableModel tabela = new DefaultTableModel(campos, 0);
        
        String sql = "SELECT rm_aluno, nm_aluno, nm_curso FROM tb_aluno";
        
        try(Connection conn = Conexaobanco.conectar()) {
            Statement status = conn.createStatement();
            ResultSet resultado = status.executeQuery(sql);
            
            while(resultado.next()) {
                Object[] linha = {resultado.getInt("rm_aluno"), resultado.getString("nm_aluno") , resultado.getString("nm_curso")};
                tabela.addRow(linha);
            }
            
            jTable1.setModel(tabela);
        } catch(SQLException e ) {
            throw new RuntimeException("Erro ao conectar!", e);
        }
    }//GEN-LAST:event_jButton5ActionPerformed

