    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        
        String rm;
        String nome;
        String idade;
        
        rm = txtRM.getText();
        nome = txtNome.getText();
        idade = txtIdade.getText();
        
        String sql = "INSERT INTO tb_aluno (rm_aluno, nm_aluno, nm_curso) VALUES (?, ?, ?)";
        
        try(Connection conn = Conexaobanco.conectar()) {
            PreparedStatement mensagem = conn.prepareStatement(sql);
            mensagem.setString(1, rm);
            mensagem.setString(2, nome);
            mensagem.setString(3, String.valueOf(idade));
            mensagem.executeUpdate();
            
        } catch(SQLException e ) {
            throw new RuntimeException("Erro ao conectar!", e);
        }
    }//GEN-LAST:event_jButton3ActionPerformed

