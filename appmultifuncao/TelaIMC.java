    private void jBtnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnCalcularActionPerformed
        double imc = Double.parseDouble(jTFPeso.getText()) / Math.pow(Double.parseDouble(jTFAltura.getText()), 2);
        String resultado = String.format("%.2f", imc) + ". Clássificado como: ";
        
        if (imc < 18.5) {
            resultado += "Abaixo do peso";
        } else if (imc >= 18.5 && imc <= 24.9) {
            resultado += "Peso normal(ideal)";
        } else if (imc >= 25.0 && imc <= 29.9) {
            resultado += "Sobrepeso";
        } else if (imc >= 30.0 && imc <= 34.9) {
            resultado += "Obesidade Grau I";
        }  else if (imc >= 35.0 && imc <= 39.9) {
            resultado += "Obesidade Grau II";
        } else {
            resultado += "Obesidade Grau III";
        }
        
        jLblResultado.setText(resultado);
    }//GEN-LAST:event_jBtnCalcularActionPerformed

